#!/usr/bin/env bash
# Proposes the files a workflow generated in a pull request, when they changed.
# Usage: propose-changes.sh <branch suffix> <commit message> <path>...
# Needs GH_TOKEN (contents and pull requests: write) and REPOSITORY (owner/name).
set -euo pipefail

suffix="$1"
message="$2"
shift 2

if [ -z "$(git status --porcelain -- "$@")" ]; then
  echo "Nothing changed."
  exit 0
fi

branch="automation/$suffix"
git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
git switch --create "$branch"
git add -- "$@"
git commit --quiet --message "$message"

# The token goes in a header (never in the remote address, which git may print)
auth="$(printf 'x-access-token:%s' "$GH_TOKEN" | base64 --wrap=0)"
git -c "http.https://github.com/.extraheader=AUTHORIZATION: basic $auth" \
  push --force "https://github.com/$REPOSITORY.git" "HEAD:refs/heads/$branch"

if [ -z "$(gh pr list --repo "$REPOSITORY" --head "$branch" --state open --json number --jq '.[].number')" ]; then
  gh pr create --repo "$REPOSITORY" --head "$branch" --title "$message" \
    --body "Generated by the \`${GITHUB_WORKFLOW:-automation}\` workflow. Close and reopen this pull request to run the checks."
fi
