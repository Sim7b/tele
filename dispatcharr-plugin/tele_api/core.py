@dataclass(frozen=True)
class ProfileLimit:
    profile_id: int
    account_id: int
    account_name: str
    max_streams: int  # 0: unlimited
    active: bool


def slots(profiles: Iterable[ProfileLimit], used_by_profile: Mapping[int, int]) -> Dict[str, Any]:
    """Free provider connections by account and in total.

    Only active profiles of active accounts count. A profile without limit makes its account unlimited; the
    total only sums the limited profiles (like the Télé header), and "unlimited" says some account has none.
    The connections in use come from the counters Dispatcharr itself checks before opening a stream.
    """
    accounts: Dict[int, Dict[str, Any]] = {}
    for profile in profiles:
        if not profile.active:
            continue
        account = accounts.setdefault(
            profile.account_id,
            {"id": profile.account_id, "name": profile.account_name, "total": 0, "used": 0, "unlimited": False},
        )
        if profile.max_streams <= 0:
            account["unlimited"] = True
            continue
        account["total"] += profile.max_streams
        used = max(0, to_int(used_by_profile.get(profile.profile_id), 0) or 0)
        account["used"] += min(used, profile.max_streams)

    total = used = 0
    for account in accounts.values():
        account["free"] = max(0, account["total"] - account["used"])
        total += account["total"]
        used += account["used"]
    return {
        "total": total,
        "used": used,
        "free": max(0, total - used),
        "unlimited": any(a["unlimited"] for a in accounts.values()),
        "limited": total > 0,
        "accounts": sorted(accounts.values(), key=lambda a: (a["name"].lower(), a["id"])),
    }


