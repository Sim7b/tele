"""Pure helpers of the Télé API plugin: no Django, no Redis, unit tested on their own.

Everything coming from the request or from Redis is untrusted: helpers clamp sizes, validate ids and never
raise on malformed values.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from typing import Any, Dict, Iterable, List, Mapping, Optional, Tuple

API_VERSION = 1
# Same as plugin.json (checked by the tests)
PLUGIN_VERSION = "0.2.0"

DEFAULT_PAGE_SIZE = 1000
MAX_PAGE_SIZE = 5000

# Live client ids are "client_<ms>_<rand>"; VOD session ids are generated by the server too. Anything else
# (path separators, wildcards, huge strings) is refused before it reaches a Redis key.
_SESSION_PART_RE = re.compile(r"^[A-Za-z0-9_.:\-]{1,128}$")
SESSION_KINDS = ("live", "vod")


def to_text(value: Any) -> Optional[str]:
    """Redis value as text (bytes decoded, empty and "None" as None)."""
    if value is None:
        return None
    if isinstance(value, bytes):
        value = value.decode("utf-8", errors="replace")
    text = str(value)
    return text if text and text != "None" else None


def to_int(value: Any, default: Optional[int] = None) -> Optional[int]:
    try:
        return int(str(to_text(value)).strip())
    except (TypeError, ValueError):
        return default


def to_float(value: Any, default: Optional[float] = None) -> Optional[float]:
    try:
        result = float(str(to_text(value)).strip())
    except (TypeError, ValueError):
        return default
    return result if result == result and result not in (float("inf"), float("-inf")) else default


def query_int(value: Any, default: int, minimum: int, maximum: int) -> int:
    """Integer query parameter clamped to [minimum, maximum]; default when missing or malformed."""
    parsed = to_int(value, default)
    return max(minimum, min(maximum, parsed if parsed is not None else default))


def query_bool(value: Any) -> bool:
    return (to_text(value) or "").lower() in ("1", "true", "yes", "on")


@dataclass(frozen=True)
class Page:
    number: int
    size: int
    count: int

    @property
    def pages(self) -> int:
        return max(1, -(-self.count // self.size))

    @property
    def start(self) -> int:
        return min(self.count, (self.number - 1) * self.size)

    @property
    def end(self) -> int:
        return min(self.count, self.start + self.size)


def page_of(count: int, page: Any, page_size: Any) -> Page:
    """Bounds of a page; a page past the end is empty (clients read pages until a short one)."""
    size = query_int(page_size, DEFAULT_PAGE_SIZE, 1, MAX_PAGE_SIZE)
    total = max(0, int(count))
    return Page(number=query_int(page, 1, 1, 1_000_000), size=size, count=total)


def etag(payload: Any) -> str:
    """Strong ETag of a JSON payload (canonical form: sorted keys, no spaces)."""
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False, default=str)
    return '"' + hashlib.sha256(canonical.encode("utf-8")).hexdigest()[:32] + '"'


def etag_matches(if_none_match: Optional[str], current: str) -> bool:
    if not if_none_match:
        return False
    candidates = [part.strip() for part in if_none_match.split(",")]
    bare = current.strip('"')
    return any(c == "*" or c == current or c.removeprefix("W/").strip('"') == bare for c in candidates)


def effective(base: Any, override: Any) -> Any:
    """Value of a channel field once its override (Dispatcharr ChannelOverride) is applied."""
    return override if override is not None else base


def channel_number(value: Any) -> Optional[float]:
    number = to_float(value)
    if number is None or number <= 0:
        return None
    return int(number) if number.is_integer() else number


