def session_id(kind: str, channel_key: Optional[str], client_id: str) -> str:
    return f"{kind}:{channel_key}:{client_id}" if kind == "live" else f"{kind}:{client_id}"


def parse_session_id(value: Any) -> Optional[Tuple[str, Optional[str], str]]:
    """(kind, channel key, client id) of a session id built by [session_id]; None when malformed."""
    text = to_text(value)
    if not text or len(text) > 300:
        return None
    kind, _, rest = text.partition(":")
    if kind == "live":
        channel_key, _, client_id = rest.partition(":")
        if _SESSION_PART_RE.match(channel_key or "") and _SESSION_PART_RE.match(client_id or ""):
            return kind, channel_key, client_id
        return None
    if kind == "vod" and _SESSION_PART_RE.match(rest or ""):
        return kind, None, rest
    return None


@dataclass(frozen=True)
class Session:
    kind: str
    client_id: str
    channel_key: Optional[str]
    title: Optional[str]
    user_id: Optional[str]
    ip: Optional[str]
    user_agent: Optional[str]
    connected_at: Optional[float]
    profile_id: Optional[int]

    @property
    def id(self) -> str:
        return session_id(self.kind, self.channel_key, self.client_id)


def is_same_device(session: Session, ip: Optional[str], user_agent: Optional[str]) -> bool:
    """Same address and player as the request: most likely the TV asking (best effort, no device id)."""
    return bool(ip) and session.ip == ip and (session.user_agent or "") == (user_agent or "")


def visible_sessions(
    sessions: Iterable[Session],
    user_id: Any,
    *,
    admin: bool,
    everyone: bool,
    ip: Optional[str],
    user_agent: Optional[str],
    usernames: Optional[Mapping[str, str]] = None,
) -> List[Dict[str, Any]]:
    """Sessions the caller may see, as JSON: their own; every user's for an admin asking for all."""
    owner = str(user_id)
    result = []
    for session in sessions:
        own = session.user_id == owner
        if not own and not (admin and everyone):
            continue
        data: Dict[str, Any] = {
            "id": session.id,
            "kind": session.kind,
            "title": session.title,
            "connected_at": session.connected_at,
            "mine": own,
            "this_device": own and is_same_device(session, ip, user_agent),
        }
        if session.channel_key:
            data["channel"] = session.channel_key
        if admin:
            # Viewer details only for admins: the address of other TVs is not shared with standard users
            data["user_agent"] = session.user_agent
            data["ip"] = session.ip
            if usernames is not None and session.user_id is not None:
                data["user"] = usernames.get(session.user_id)
        result.append(data)
    result.sort(key=lambda s: (-(s["connected_at"] or 0.0), s["id"]))
    return result


def may_release(session: Optional[Session], user_id: Any, *, admin: bool) -> bool:
    return session is not None and (admin or session.user_id == str(user_id))
