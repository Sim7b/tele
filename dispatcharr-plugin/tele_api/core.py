def iso(value: Any) -> Optional[str]:
    if value is None:
        return None
    isoformat = getattr(value, "isoformat", None)
    return isoformat() if callable(isoformat) else to_text(value)


def now_and_next(programs: Iterable[Mapping[str, Any]], now: Any) -> Dict[Any, Dict[str, Any]]:
    """Current and next program by EPG id, from programs sorted by (epg_id, start).

    Each program is a mapping with epg_id, title, sub_title, start, end (datetimes or comparable values).
    A gap before the first program leaves "now" empty and keeps it as "next".
    """
    result: Dict[Any, Dict[str, Any]] = {}
    for program in programs:
        epg_id = program.get("epg_id")
        start, end = program.get("start"), program.get("end")
        if epg_id is None or start is None or end is None or end <= now:
            continue
        slot = result.setdefault(epg_id, {})
        if "next" in slot:
            continue
        if start <= now and "now" not in slot:
            slot["now"] = program_json(program)
        elif start > now:
            slot["next"] = program_json(program)
    return result


def program_json(program: Mapping[str, Any]) -> Dict[str, Any]:
    data = {
        "title": to_text(program.get("title")) or "",
        "start": iso(program.get("start")),
        "end": iso(program.get("end")),
    }
    sub_title = to_text(program.get("sub_title"))
    if sub_title:
        data["sub_title"] = sub_title[:512]
    return data


